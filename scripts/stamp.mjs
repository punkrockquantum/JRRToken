/**
 * Writes a short build stamp into js/build-info.js and cache-busts index.html.
 * Run before start so a kiosk refresh is obviously the latest code.
 */
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"

const sources = ["js/main.js", "js/intro.js", "js/data.js", "js/model.js", "css/game.css"]
const hash = createHash("sha1")
for (const file of sources) hash.update(readFileSync(file))
const digest = hash.digest("hex").slice(0, 7)
const when = new Date().toISOString().slice(2, 16).replace(/[-:T]/g, "")
const stamp = `${when}-${digest}`

writeFileSync(
  "js/build-info.js",
  `/** Generated by scripts/stamp.mjs. Shows which build the browser is running. */\nexport const BUILD = { stamp: ${JSON.stringify(stamp)} }\n`,
)
const page = readFileSync("index.html", "utf8")
const next = page.replace(/src="js\/main\.js(?:\?v=[^"]*)?"/, `src="js/main.js?v=${stamp}"`)
if (next === page) throw new Error("index.html has no js/main.js script tag to stamp")
writeFileSync("index.html", next)
console.log(stamp)
