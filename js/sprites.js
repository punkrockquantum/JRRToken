/* ---------- Pixel text ---------- */

export const FONT = "'Press Start 2P', monospace"
/** Press Start 2P draws every glyph on an 8x8 grid, so the advance is always 8. */
export const GLYPH = 8
const SAMPLE = 16

const glyphBits = new Map()
const glyphCache = new Map()
let sampler = null

/** Resolves once the pixel font is available (or immediately when it cannot be). */
export function fontReady() {
  if (typeof document === "undefined" || !document.fonts?.load) return Promise.resolve()
  return document.fonts.load(`${GLYPH}px ${FONT}`).then(
    () => undefined,
    () => undefined,
  )
}

function fontLoaded() {
  return typeof document !== "undefined" && Boolean(document.fonts?.check?.(`${GLYPH}px ${FONT}`))
}

/**
 * Sample one glyph into an 8x8 bitmap. The glyph is drawn large and read from the
 * middle of each font pixel, so anti-aliasing never leaks into the bitmap.
 */
function bitsFor(ch) {
  const cached = glyphBits.get(ch)
  if (cached) return cached
  if (!sampler) {
    sampler = document.createElement("canvas")
    sampler.width = GLYPH * SAMPLE
    sampler.height = GLYPH * SAMPLE
  }
  const ctx = sampler.getContext("2d", { willReadFrequently: true })
  ctx.clearRect(0, 0, sampler.width, sampler.height)
  ctx.font = `${GLYPH * SAMPLE}px ${FONT}`
  ctx.textAlign = "left"
  ctx.textBaseline = "top"
  ctx.fillStyle = "#fff"
  ctx.fillText(ch, 0, 0)
  const data = ctx.getImageData(0, 0, sampler.width, sampler.height).data
  const rows = []
  for (let y = 0; y < GLYPH; y += 1) {
    let row = 0
    for (let x = 0; x < GLYPH; x += 1) {
      const index = ((y * SAMPLE + SAMPLE / 2) * sampler.width + x * SAMPLE + SAMPLE / 2) * 4 + 3
      if (data[index] > 127) row |= 1 << x
    }
    rows.push(row)
  }
  if (fontLoaded()) glyphBits.set(ch, rows)
  return rows
}

function glyphCanvas(ch, scale, color) {
  const key = `${ch}|${scale}|${color}`
  const hit = glyphCache.get(key)
  if (hit) return hit
  const rows = bitsFor(ch)
  const canvas = document.createElement("canvas")
  canvas.width = GLYPH * scale
  canvas.height = GLYPH * scale
  const ctx = canvas.getContext("2d")
  ctx.fillStyle = color
  rows.forEach((row, y) => {
    for (let x = 0; x < GLYPH; x += 1) {
      if (row & (1 << x)) ctx.fillRect(x * scale, y * scale, scale, scale)
    }
  })
  if (glyphBits.has(ch)) glyphCache.set(key, canvas)
  return canvas
}

/** Width of a label in canvas pixels at an integer scale. */
export function textWidth(value, scale = 1) {
  return String(value).length * GLYPH * Math.max(1, Math.round(scale))
}

/**
 * Crisp pixel-font label for canvases. Glyphs are 8x8 bitmaps of Press Start 2P drawn
 * at an integer scale with a fixed advance, so letters never collide, blur, or cast a
 * shadow. Returns the drawn width in canvas pixels.
 */
export function text(ctx, value, x, y, { scale = 1, color = PALETTE.w, align = "left" } = {}) {
  const s = Math.max(1, Math.round(scale))
  const str = String(value)
  const advance = GLYPH * s
  const width = str.length * advance
  let left = Math.round(x)
  if (align === "center") left -= Math.floor(width / 2)
  else if (align === "right") left -= width
  const top = Math.round(y)
  ctx.save()
  ctx.imageSmoothingEnabled = false
  for (let i = 0; i < str.length; i += 1) {
    const ch = str[i]
    if (ch === " ") continue
    ctx.drawImage(glyphCanvas(ch, s, color), left + i * advance, top)
  }
  ctx.restore()
  return width
}

/**
 * Size a canvas so one logical pixel is a whole number of device pixels and the CSS
 * box matches the backing store exactly. No resampling, so sprites and text stay sharp.
 */
export function fitCanvas(canvas, width, height) {
  const dpr = window.devicePixelRatio || 1
  const host = canvas.parentElement
  let availW = width
  let availH = Infinity
  if (host) {
    const box = getComputedStyle(host)
    availW = host.clientWidth - parseFloat(box.paddingLeft) - parseFloat(box.paddingRight)
    availH = host.clientHeight - parseFloat(box.paddingTop) - parseFloat(box.paddingBottom)
    if (!(availH > 0)) availH = Infinity
  }
  // Whole-number scale only, so the pixel font never blurs; fits the host by width and height.
  const scale = Math.max(1, Math.floor(Math.min((availW * dpr) / width, (availH * dpr) / height)))
  if (canvas.width !== width * scale || canvas.height !== height * scale) {
    canvas.width = width * scale
    canvas.height = height * scale
    canvas.style.width = `${(width * scale) / dpr}px`
    canvas.style.height = `${(height * scale) / dpr}px`
  }
  const ctx = canvas.getContext("2d")
  ctx.setTransform(scale, 0, 0, scale, 0, 0)
  ctx.imageSmoothingEnabled = false
  return { ctx, scale }
}
