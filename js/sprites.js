const cache = new Map()

function normalise(rows) {
  const width = Math.max(...rows.map((row) => row.length))
  return rows.map((row) => row.padEnd(width, ".").slice(0, width))
}

export function spriteSize(name) {
  const rows = ART[name]
  if (!rows) return { w: 0, h: 0 }
  return { w: Math.max(...rows.map((row) => row.length)), h: rows.length }
}

export function spriteCanvas(name, scale = 1) {
  const key = `${name}@${scale}`
  if (cache.has(key)) return cache.get(key)
  const rows = normalise(ART[name] || ["k"])
  const canvas = document.createElement("canvas")
  canvas.width = rows[0].length * scale
  canvas.height = rows.length * scale
  const ctx = canvas.getContext("2d")
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      const color = PALETTE[row[x]]
      if (!color) continue
      ctx.fillStyle = color
      ctx.fillRect(x * scale, y * scale, scale, scale)
    }
  })
  cache.set(key, canvas)
  return canvas
}

export function spriteImg(name, scale = 3, alt = "") {
  const img = document.createElement("img")
  img.src = spriteCanvas(name, scale).toDataURL()
  img.alt = alt
  img.className = "sprite"
  img.width = spriteCanvas(name, scale).width
  img.height = spriteCanvas(name, scale).height
  if (!alt) img.setAttribute("aria-hidden", "true")
  return img
}

export function drawSprite(ctx, name, x, y, scale = 1, flip = false) {
  const canvas = spriteCanvas(name, 1)
  ctx.save()
  ctx.imageSmoothingEnabled = false
  if (flip) {
    ctx.translate(Math.round(x) + canvas.width * scale, Math.round(y))
    ctx.scale(-1, 1)
    ctx.drawImage(canvas, 0, 0, canvas.width * scale, canvas.height * scale)
  } else {
    ctx.drawImage(canvas, Math.round(x), Math.round(y), canvas.width * scale, canvas.height * scale)
  }
  ctx.restore()
}

