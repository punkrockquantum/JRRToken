"""Regenerate the files under reports/out/.

No prose. Numbers, bounds, scope statements and tier labels only; the lint in
``reports/lint.py`` runs over everything this script writes, and
``scripts/ci_checks.py`` fails the build if a forbidden term appears.

Run:  python scripts/render_reports.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from harness.registry import REGISTRY  # noqa: E402
from modules.degree import spec as degree_spec  # noqa: E402  (registers the module)
from modules.hod import spec as hod_spec  # noqa: E402  (registers the module)
from modules.reach import spec as reach_spec  # noqa: E402  (registers the module)
from modules.differential import spec as diff_spec  # noqa: E402  (registers the module)
from modules.degree.calibration import exhaustive_truth, witness_truth  # noqa: E402
from modules.degree.calibration.suite import SUITE  # noqa: E402
from modules.degree.prereg.derive_thresholds import render_block  # noqa: E402
from provenance import gitinfo  # noqa: E402
from provenance.prereg import load as load_prereg  # noqa: E402
from reports.lint import OUT_DIR, lint_text  # noqa: E402

assert degree_spec.SPEC.module_id in REGISTRY.ids()
assert hod_spec.SPEC.module_id in REGISTRY.ids()
assert reach_spec.SPEC.module_id in REGISTRY.ids()
assert diff_spec.SPEC.module_id in REGISTRY.ids()


def registry_report() -> str:
    lines = [f"commit={gitinfo.head_commit()}", f"modules={len(REGISTRY.ids())}"]
    for module_id in REGISTRY.ids():
        spec = REGISTRY.get(module_id)
        lines.append(spec.render())
        status = spec.suite.gate()
        lines.append("  " + status.render())
    return "\n".join(lines) + "\n"


def prereg_report() -> str:
    prereg = load_prereg(degree_spec.PREREG_PATH)
    lines = [
        f"commit={gitinfo.head_commit()}",
        f"prereg_id={prereg.prereg_id}",
        f"prereg_path={prereg.relative_path}",
        f"prereg_sha256={prereg.sha256}",
        f"prereg_introducing_commit={prereg.introducing_commit()}",
        f"runner_introducing_commit={gitinfo.introducing_commit(degree_spec.SPEC.runner_path)}",
    ]
    for key in sorted(prereg.fields):
        lines.append(f"{key}={prereg.fields[key]}")
    lines.append("")
    lines.append(render_block())
    return "\n".join(lines) + "\n"


def calibration_report() -> str:
    return f"commit={gitinfo.head_commit()}\n" + SUITE.manifest() + "\n"


def exhaustive_report() -> str:
    """The committed exhaustive table, rendered from the same rows the
    calibration cases read. Regenerated by scripts/exhaust.py, which is the
    computation; this only formats it, so the report cannot drift from the
    values the suite asserts against."""
    lines = [
        f"commit={gitinfo.head_commit()}",
        f"tier=E method=full-domain-moebius sampled=none",
        f"computation_id={exhaustive_truth.COMPUTATION_ID_KECCAK} "
        f"target=keccak-f[{exhaustive_truth.KECCAK_WIDTH}] "
        f"space=2^{exhaustive_truth.KECCAK_WIDTH}",
    ]
    for row in exhaustive_truth.KECCAK_EXACT:
        lines.append(
            "  " + " ".join(f"{k}={v}" for k, v in row.items())
        )
    lines.append(
        f"computation_id={exhaustive_truth.COMPUTATION_ID_MIMC} "
        f"target=mimc-gf2n[{exhaustive_truth.MIMC_N}] "
        f"space=2^{exhaustive_truth.MIMC_N} seed={exhaustive_truth.MIMC_SEED}"
    )
    for row in exhaustive_truth.MIMC_EXACT:
        lines.append(
            "  " + " ".join(f"{k}={v}" for k, v in row.items())
        )
    lines.append(
        "scope=these values are computations in this repository and carry no "
        "citation; they do not fill the published-ground-truth cases, which "
        "remain PENDING_PRIMARY_SOURCE. escalation=E-09"
    )
    return "\n".join(lines) + "\n"


def witness_report() -> str:
    """The witness-probe calibration, rendered from the committed cells.

    Two arms with different epistemic force, so the report labels each rather
    than presenting one table of numbers: the cells above the exact degree are a
    deductive check, the cells at or below it are a sampled rate.
    """
    cells = [c for e in witness_truth.WITNESS_CELLS for c in e["cells"]]
    above = [c for c in cells if not c["witness_possible"]]
    below = [c for c in cells if c["witness_possible"]]
    lines = [
        f"commit={gitinfo.head_commit()}",
        f"computation_id={witness_truth.COMPUTATION_ID} "
        f"seeds_per_cell={witness_truth.SEEDS_PER_CELL} "
        f"seed_base={witness_truth.SEED_BASE} confidence={witness_truth.CONFIDENCE}",
        f"tier_P_cells={len(above)} draws={len(above) * witness_truth.SEEDS_PER_CELL} "
        f"witnesses={sum(int(c['witnessed']) for c in above)} "
        f"soundness_violations={len(witness_truth.soundness_violations())}",
        f"tier_S_cells={len(below)} "
        f"cells_whose_interval_excludes_the_worst_case_from_below="
        f"{sum(1 for c in below if c['ci_low'] > c['worst_case_p'])}",
    ]
    for entry in witness_truth.WITNESS_CELLS:
        lines.append(
            f"target={entry['target']} n={entry['n']} exact_degree={entry['exact_degree']}"
        )
        for cell in entry["cells"]:
            lines.append("  " + " ".join(f"{k}={v}" for k, v in cell.items()))
        for skip in entry["skipped"]:
            lines.append(
                f"  k={skip['k']} skipped=cost "
                f"evaluations_per_seed={skip['cost_evaluations_per_seed']} "
                f"guard=MAX_PROBE_DIM={witness_truth.MAX_PROBE_DIM}"
            )
    lines.append(
        "scope=rates are measured on targets whose degree is known; the promotion "
        "case is a target whose degree is unknown, so these do not bear on it. "
        "D-010 is unchanged by this computation. escalation=E-01"
    )
    return "\n".join(lines) + "\n"


REPORTS = {
    "module-registry.txt": registry_report,
    "M1-prereg.txt": prereg_report,
    "M1-calibration-manifest.txt": calibration_report,
    "M1-exhaustive.txt": exhaustive_report,
    "M1-witness.txt": witness_report,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--out-dir",
        default=None,
        help=(
            "where to write; defaults to reports/out/. Rendering into the tracked "
            "directory rewrites committed files with a fresh commit stamp, so the "
            "working tree is dirty afterwards and any provenance run executed later "
            "records working_tree_clean=False. The test suite renders elsewhere."
        ),
    )
    args = parser.parse_args()
    out_dir = Path(args.out_dir) if args.out_dir else OUT_DIR

    out_dir.mkdir(parents=True, exist_ok=True)
    failures = 0
    for name, builder in REPORTS.items():
        text = builder()
        hits = lint_text(text, path=f"{out_dir}/{name}")
        if hits:
            failures += len(hits)
            for hit in hits:
                print(hit.render())
            continue
        (out_dir / name).write_text(text, encoding="utf-8")
        print(f"wrote={name} dir={out_dir} bytes={len(text.encode('utf-8'))}")
    if failures:
        print(f"refused_to_write={failures}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
